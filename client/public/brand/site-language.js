  function translateAttributes(element) {
    if (!eligible(element)) return;
    let originals = attributeSources.get(element);
    for (const name of ["aria-label", "alt", "title", "placeholder"]) {
      const current = element.getAttribute(name);
      if (!current) continue;
      const previous = originals?.[name];
      const source = previous && current === previous.rendered ? previous.source : current;
      const rendered = translate(source);
      if (current !== rendered) element.setAttribute(name, rendered);
      if (source !== rendered || previous) {
        originals ||= {};
        originals[name] = { source, rendered };
      }
    }
    if (originals) attributeSources.set(element, originals);
  }
